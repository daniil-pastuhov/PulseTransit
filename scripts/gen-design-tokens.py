#!/usr/bin/env python3
"""Generates the apps' colour and dimension tokens from the Fjord design tokens.

docs/design/tokens.json is the single source of truth. This writes
ui/src/commonMain/kotlin/com/example/pulsetransit/theme/FjordTokens.kt (Compose) and
iosApp/JourneyActivityShared/FjordTokens.swift (SwiftUI); commit both. It also checks the contrast pairs
the tokens declare and fails if one is below WCAG AA (4.5:1 for text, 3:1 for large text).

    scripts/gen-design-tokens.py          # rewrite both files
    scripts/gen-design-tokens.py --check  # exit 1 if either is out of date or a pair fails (for CI)
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "docs/design/tokens.json"
KOTLIN = ROOT / "ui/src/commonMain/kotlin/com/example/pulsetransit/theme/FjordTokens.kt"
SWIFT = ROOT / "iosApp/JourneyActivityShared/FjordTokens.swift"
HEADER = "Generated by scripts/gen-design-tokens.py from docs/design/tokens.json. Do not edit."
MINIMUM = {"text": 4.5, "large-text": 3.0}


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def resolve(value, primitives):
    """'{slate.50}' -> '#F2F4F7'; literal hex values pass through."""
    match = re.fullmatch(r"\{([a-z]+)\.([0-9a-z]+)\}", value)
    if match:
        value = primitives[match.group(1)][match.group(2)]
    if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
        sys.exit(f"Not a #RRGGBB colour: {value}")
    return value[1:].upper()


def themes(tokens):
    primitives = tokens["primitives"]["color"]
    out = {}
    for theme in ("light", "dark"):
        out[theme] = {name: resolve(value, primitives) for name, value in tokens["color"][theme].items()}
    if out["light"].keys() != out["dark"].keys():
        sys.exit("Light and dark themes define different colour roles")
    return out


def luminance(hex_rgb):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex_rgb[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check_contrast(tokens, colours):
    failures = []
    for pair in tokens["contrast"]:
        backgrounds = pair["bg"] if isinstance(pair["bg"], list) else [pair["bg"]]
        for theme, roles in colours.items():
            for bg in backgrounds:
                ratio = contrast(roles[pair["fg"]], roles[bg])
                if ratio < MINIMUM[pair["use"]]:
                    failures.append(f"{theme}: {pair['fg']} on {bg} is {ratio:.2f}:1, needs {MINIMUM[pair['use']]}")
    return failures


def kotlin(tokens, colours):
    lines = [f"// {HEADER}", "package com.example.pulsetransit.theme", "", "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", ""]
    for theme, roles in colours.items():
        lines.append(f"/** The {theme} theme's colour roles. */")
        lines.append(f"internal object Fjord{theme.capitalize()} {{")
        lines += [f"    val {camel(name)} = Color(0xFF{hex_rgb})" for name, hex_rgb in roles.items()]
        lines += ["}", ""]
    lines.append("/** Spacing, corner radii and component sizes, in dp. */")
    lines.append("internal object FjordDimens {")
    lines += [f"    val space{key} = {value}.dp" for key, value in tokens["space"].items()]
    lines += [f"    val radius{key.capitalize()} = {value}.dp" for key, value in tokens["radius"].items() if key != "full"]
    lines += [f"    val {camel(key)} = {value}.dp" for key, value in tokens["size"].items()]
    lines += ["}", ""]
    lines.append("/** A type role: size and line height in sp, weight 100–900, tracking in sp. */")
    # The multi-line signature ktlint_official wants, so ktlintFormat leaves the file as generated.
    lines += [
        "internal data class TypeRole(",
        "    val size: Int,",
        "    val line: Int,",
        "    val weight: Int,",
        "    val tracking: Float = 0f,",
        ")",
    ]
    lines.append("")
    lines.append("/** The type roles. */")
    lines.append("internal object FjordType {")
    for key, role in tokens["type"].items():
        tracking = f", {role['tracking']}f" if role.get("tracking") else ""
        lines.append(f"    val {camel(key)} = TypeRole({role['size']}, {role['line']}, {role['weight']}{tracking})")
    lines += ["}", ""]
    return "\n".join(lines)


def swift(tokens, colours):
    lines = [f"// {HEADER}", "", "/// Colour roles as (light, dark) RGB pairs, and dimensions in points.", "enum FjordTokens {"]
    for name in colours["light"]:
        lines.append(f"    static let {camel(name)}: (light: UInt32, dark: UInt32) = (0x{colours['light'][name]}, 0x{colours['dark'][name]})")
    lines.append("")
    lines += [f"    static let space{key}: CGFloat = {value}" for key, value in tokens["space"].items()]
    lines += [f"    static let radius{key.capitalize()}: CGFloat = {value}" for key, value in tokens["radius"].items() if key != "full"]
    lines += [f"    static let {camel(key)}: CGFloat = {value}" for key, value in tokens["size"].items()]
    lines.append("")
    lines.append("    /// Type roles: size and line height in points, weight 100–900, tracking in points.")
    for key, role in tokens["type"].items():
        lines.append(
            f"    static let type{camel(key)[0].upper() + camel(key)[1:]}: (size: CGFloat, line: CGFloat, weight: Int, tracking: CGFloat) = "
            f"({role['size']}, {role['line']}, {role['weight']}, {role.get('tracking', 0)})"
        )
    lines += ["}", ""]
    return "\n".join(["import CoreGraphics", ""] + lines)


def main():
    check = "--check" in sys.argv[1:]
    tokens = json.loads(TOKENS.read_text())
    colours = themes(tokens)
    failures = check_contrast(tokens, colours)
    if failures:
        sys.exit("Contrast below WCAG AA:\n  " + "\n  ".join(failures))
    outputs = {KOTLIN: kotlin(tokens, colours), SWIFT: swift(tokens, colours)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if check:
        if stale:
            sys.exit("Out of date, run scripts/gen-design-tokens.py: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return
    for path in stale:
        path.write_text(outputs[path])
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
