"""Generates the Compose icon set from Material Symbols Rounded (Apache License 2.0).

The Fjord design uses one icon family, Material Symbols Rounded at weight 400 (SF Symbols on iOS).
Only the icons listed in ICONS are bundled: this downloads each one's SVG from
github.com/google/material-design-icons and writes
ui/src/commonMain/kotlin/com/example/pulsetransit/theme/PulseIcons.kt, with one ImageVector per
icon built from the SVG path. Add a name to ICONS, rerun, and commit the result.

    scripts/gen-icons.py
"""

