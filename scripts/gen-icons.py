# Icons that point along the reading direction, so they flip in right-to-left layouts.
AUTO_MIRRORED = {"arrow_back", "arrow_forward", "chevron_left", "chevron_right", "directions_walk", "open_in_new"}


def kotlin_name(name, filled):
    return "".join(part.capitalize() for part in name.split("_")) + ("Filled" if filled else "")


def fetch(job):
    name, filled = job
    with urllib.request.urlopen(URL.format(name=name, fill="_fill1" if filled else "")) as response:
        svg = response.read().decode()
    if 'viewBox="0 -960 960 960"' not in svg:
        sys.exit(f"{name}: unexpected viewBox")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        sys.exit(f"{name}: no path")
    return name, filled, paths


def main():
    jobs = [(name, False) for name in ICONS] + [(name, True) for name, filled in ICONS.items() if filled]
    with ThreadPoolExecutor(max_workers=16) as pool:
        icons = sorted(pool.map(fetch, jobs), key=lambda icon: kotlin_name(icon[0], icon[1]))
    lines = [
        "// Generated by scripts/gen-icons.py from Material Symbols Rounded (Apache License 2.0).",
        "// Do not edit; add the icon to the script and rerun it.",
        "@file:Suppress(\"ktlint\", \"MaxLineLength\", \"LargeClass\")",
        "",
        "package com.example.pulsetransit.theme",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** The app's icons: Material Symbols Rounded, weight 400, outlined unless the name ends in Filled. */",
        "object PulseIcons {",
    ]
    for name, filled, paths in icons:
        mirrored = "true" if name in AUTO_MIRRORED else "false"
        joined = ", ".join(f'"{path}"' for path in paths)
        lines.append(f'    val {kotlin_name(name, filled)}: ImageVector by lazy {{ symbol("{kotlin_name(name, filled)}", {mirrored}, {joined}) }}')
    lines += ["}", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {len(icons)} icons to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
